<?php

declare(strict_types=1);

namespace App\Console\Commands;

use App\Domains\IdentityAccess\Permissions\PermissionRegistry;
use App\Http\Support\ResourceRegistry;
use App\Support\Enums\EnumRegistry;
use App\Support\Exceptions\ErrorCode;
use App\Support\Schema\SchemaRegistry;
use Illuminate\Console\Command;

/**
 * `types:export-ts` (Chapter 12 §12.1): TypeScript contract generated from the backend registries —
 * enum values, permission codes, error codes, schema names and the model → API resource map used by
 * reference pickers. Never hand-edited; CI regenerates and diffs it.
 */
final class TypesExportTsCommand extends Command
{
    protected $signature = 'types:export-ts {--output=resources/js/types/generated.ts} {--check : Fail if the file is out of date}';

    protected $description = 'Generate the TypeScript contract for the frontend from the backend registries.';

    public function handle(EnumRegistry $enums, PermissionRegistry $permissions, SchemaRegistry $schemas): int
    {
        $enumValues = [];
        foreach ($enums->export() as $e) {
            $enumValues[$e['code']] = array_column($e['cases'], 'value');
        }
        ksort($enumValues);
        $permissionCodes = $permissions->all()->pluck('code')->sort()->values()->all();
        $errorCodes = array_map(fn (ErrorCode $c) => $c->value, ErrorCode::cases());
        sort($errorCodes);
        $schemaNames = $schemas->all()->keys()->all();
        sort($schemaNames);
        $references = [];
        foreach (ResourceRegistry::all() as $key => $cfg) {
            $references[class_basename($cfg['model'])] ??= $key;
        }
        ksort($references);

        $union = fn (array $values) => $values === [] ? 'never' : implode("\n    | ", array_map(fn ($v) => json_encode($v), $values));
        $ts = "// Generated by `php artisan types:export-ts` — do not edit.\n\n"
            ."export const ENUM_VALUES = ".json_encode($enumValues, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES)." as const;\n\n"
            ."export type EnumCode = keyof typeof ENUM_VALUES;\n"
            ."export type EnumValue<C extends EnumCode> = (typeof ENUM_VALUES)[C][number];\n\n"
            ."export type PermissionCode =\n    | ".$union($permissionCodes).";\n\n"
            ."export type ErrorCode =\n    | ".$union($errorCodes).";\n\n"
            ."export type SchemaName =\n    | ".$union($schemaNames).";\n\n"
            ."/** Model (as named in schema `references`) → API resource key for pickers. */\n"
            ."export const REFERENCE_RESOURCES: Record<string, string> = ".json_encode($references, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES).";\n";
        $ts = str_replace('    ', '  ', $ts);

        $path = base_path((string) $this->option('output'));
        if ($this->option('check')) {
            if (! is_file($path) || file_get_contents($path) !== $ts) {
                $this->error("$path is out of date; run php artisan types:export-ts.");

                return self::FAILURE;
            }
            $this->info('TypeScript contract is up to date.');

            return self::SUCCESS;
        }
        if (! is_dir(dirname($path))) {
            mkdir(dirname($path), 0775, true);
        }
        file_put_contents($path, $ts);
        $this->info('Wrote '.count($enumValues).' enums, '.count($permissionCodes).' permissions, '.count($errorCodes).' error codes, '
            .count($schemaNames).' schemas to '.$this->option('output'));

        return self::SUCCESS;
    }
}
