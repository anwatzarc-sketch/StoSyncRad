<?php

declare(strict_types=1);

namespace App\Support\Exceptions;

/**
 * Machine-readable business/API error codes with their HTTP status (Chapter 11 §11.4).
 */
enum ErrorCode: string
{
    // Generic
    case VALIDATION_FAILED = 'VALIDATION_FAILED';
    case NOT_FOUND = 'NOT_FOUND';
    case UNAUTHENTICATED = 'UNAUTHENTICATED';
    case PERMISSION_DENIED = 'PERMISSION_DENIED';
    case FEATURE_DISABLED = 'FEATURE_DISABLED';
    case PROPERTY_FORBIDDEN = 'PROPERTY_FORBIDDEN';
    case SETUP_REQUIRED = 'SETUP_REQUIRED';
    case MAINTENANCE = 'MAINTENANCE';
    case RATE_LIMITED = 'RATE_LIMITED';
    case PAYLOAD_TOO_LARGE = 'PAYLOAD_TOO_LARGE';
    case UNSUPPORTED_MEDIA_TYPE = 'UNSUPPORTED_MEDIA_TYPE';
    case MALFORMED_REQUEST = 'MALFORMED_REQUEST';
    case INTERNAL_ERROR = 'INTERNAL_ERROR';
    case OPERATION_TIMEOUT = 'OPERATION_TIMEOUT';
    case STEP_UP_REQUIRED = 'STEP_UP_REQUIRED';
    case PASSWORD_CHANGE_REQUIRED = 'PASSWORD_CHANGE_REQUIRED';
    case MFA_ENROLLMENT_REQUIRED = 'MFA_ENROLLMENT_REQUIRED';

    // State / concurrency
    case INVALID_STATE_TRANSITION = 'INVALID_STATE_TRANSITION';
    case STALE_VERSION = 'STALE_VERSION';
    case ALREADY_POSTED = 'ALREADY_POSTED';
    case LOCK_TIMEOUT = 'LOCK_TIMEOUT';
    case CONSTRAINT_VIOLATION = 'CONSTRAINT_VIOLATION';
    case DUPLICATE_RESOURCE = 'DUPLICATE_RESOURCE';
    case POSITION_FROZEN = 'POSITION_FROZEN';
    case CONCURRENCY_RETRIES_EXHAUSTED = 'CONCURRENCY_RETRIES_EXHAUSTED';

    // Idempotency
    case IDEMPOTENCY_KEY_REQUIRED = 'IDEMPOTENCY_KEY_REQUIRED';
    case IDEMPOTENT_IN_PROGRESS = 'IDEMPOTENT_IN_PROGRESS';
    case IDEMPOTENCY_PAYLOAD_MISMATCH = 'IDEMPOTENCY_PAYLOAD_MISMATCH';

    // Inventory
    case INSUFFICIENT_STOCK = 'INSUFFICIENT_STOCK';
    case LOT_MISMATCH = 'LOT_MISMATCH';
    case LOT_LOCKED = 'LOT_LOCKED';
    case LOT_NOT_RELEASED = 'LOT_NOT_RELEASED';
    case STOCK_INELIGIBLE = 'STOCK_INELIGIBLE';
    case SERIAL_STATE_INVALID = 'SERIAL_STATE_INVALID';
    case REVERSAL_BLOCKED_DOWNSTREAM = 'REVERSAL_BLOCKED_DOWNSTREAM';
    case NEGATIVE_STOCK_FORBIDDEN = 'NEGATIVE_STOCK_FORBIDDEN';
    case QUANTITY_EXCEEDS_OUTSTANDING = 'QUANTITY_EXCEEDS_OUTSTANDING';
    case OVER_RECEIPT = 'OVER_RECEIPT';
    case RESERVATION_CONFLICT = 'RESERVATION_CONFLICT';
    case TRACKING_MODE_REQUIRES_LOT = 'TRACKING_MODE_REQUIRES_LOT';
    case TRACKING_MODE_REQUIRES_SERIAL = 'TRACKING_MODE_REQUIRES_SERIAL';
    case CONSERVATION_VIOLATION = 'CONSERVATION_VIOLATION';

    // Authorization / approvals
    case SOD_VIOLATION = 'SOD_VIOLATION';
    case APPROVAL_REQUIRED = 'APPROVAL_REQUIRED';
    case APPROVAL_LIMIT_EXCEEDED = 'APPROVAL_LIMIT_EXCEEDED';
    case WAREHOUSE_SCOPE_DENIED = 'WAREHOUSE_SCOPE_DENIED';
    case ACCOUNT_LIMIT_REACHED = 'ACCOUNT_LIMIT_REACHED';
    case POLICY_VIOLATION = 'POLICY_VIOLATION';

    // Reporting
    case REPORT_TOO_EXPENSIVE = 'REPORT_TOO_EXPENSIVE';
    case REPORT_CAPACITY = 'REPORT_CAPACITY';
    case REPORT_FIELD_FORBIDDEN = 'REPORT_FIELD_FORBIDDEN';
    case REPORT_DEFINITION_INVALID = 'REPORT_DEFINITION_INVALID';
    case REPORT_LIMIT_EXCEEDED = 'REPORT_LIMIT_EXCEEDED';

    // Platform
    case SETUP_STEP_ORDER = 'SETUP_STEP_ORDER';
    case SETUP_TOKEN_INVALID = 'SETUP_TOKEN_INVALID';
    case CONFIG_KEY_UNKNOWN = 'CONFIG_KEY_UNKNOWN';
    case CONFIG_VALUE_INVALID = 'CONFIG_VALUE_INVALID';
    case CONFIG_SCOPE_NOT_ALLOWED = 'CONFIG_SCOPE_NOT_ALLOWED';

    public function httpStatus(): int
    {
        return match ($this) {
            self::VALIDATION_FAILED, self::CONSTRAINT_VIOLATION, self::INSUFFICIENT_STOCK,
            self::STOCK_INELIGIBLE, self::NEGATIVE_STOCK_FORBIDDEN, self::QUANTITY_EXCEEDS_OUTSTANDING,
            self::OVER_RECEIPT, self::TRACKING_MODE_REQUIRES_LOT, self::TRACKING_MODE_REQUIRES_SERIAL,
            self::ACCOUNT_LIMIT_REACHED, self::POLICY_VIOLATION, self::IDEMPOTENCY_PAYLOAD_MISMATCH,
            self::IDEMPOTENCY_KEY_REQUIRED, self::REPORT_TOO_EXPENSIVE, self::REPORT_DEFINITION_INVALID,
            self::REPORT_LIMIT_EXCEEDED, self::CONFIG_KEY_UNKNOWN, self::CONFIG_VALUE_INVALID,
            self::CONFIG_SCOPE_NOT_ALLOWED, self::APPROVAL_REQUIRED, self::APPROVAL_LIMIT_EXCEEDED,
            self::CONSERVATION_VIOLATION, self::SETUP_STEP_ORDER => 422,
            self::NOT_FOUND => 404,
            self::UNAUTHENTICATED, self::SETUP_TOKEN_INVALID => 401,
            self::PERMISSION_DENIED, self::FEATURE_DISABLED, self::PROPERTY_FORBIDDEN,
            self::WAREHOUSE_SCOPE_DENIED, self::REPORT_FIELD_FORBIDDEN, self::STEP_UP_REQUIRED,
            self::PASSWORD_CHANGE_REQUIRED, self::MFA_ENROLLMENT_REQUIRED => 403,
            self::INVALID_STATE_TRANSITION, self::STALE_VERSION, self::ALREADY_POSTED, self::LOCK_TIMEOUT,
            self::DUPLICATE_RESOURCE, self::POSITION_FROZEN, self::IDEMPOTENT_IN_PROGRESS, self::LOT_MISMATCH,
            self::LOT_LOCKED, self::LOT_NOT_RELEASED, self::SERIAL_STATE_INVALID, self::REVERSAL_BLOCKED_DOWNSTREAM,
            self::RESERVATION_CONFLICT, self::SOD_VIOLATION, self::CONCURRENCY_RETRIES_EXHAUSTED => 409,
            self::PAYLOAD_TOO_LARGE => 413,
            self::UNSUPPORTED_MEDIA_TYPE => 415,
            self::MALFORMED_REQUEST => 400,
            self::RATE_LIMITED, self::REPORT_CAPACITY => 429,
            self::SETUP_REQUIRED, self::MAINTENANCE => 503,
            self::OPERATION_TIMEOUT => 504,
            self::INTERNAL_ERROR => 500,
        };
    }
}
